"""fontconfig files fontlab generates.

70-fontlab-render.conf  antialiasing, hinting, LCD filter, fake bold, icon fonts and
                        Droid Sans when darkening is on, hidden system fonts, Google Sans
                        aliases (here, not in 71, so they also hold for "system" and reach
                        Chromium's private config for "windows")
71-fontlab-web.conf     what sans-serif, system-ui, Arial etc. resolve to (absent for "system")
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from collections.abc import Iterable
from html import escape

from . import paths
from .state import State

HEADER = """<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by fontlab from ~/.config/fontlab/state.toml. Do not edit; run fontlab. -->
"""

RGBA = {"grayscale": "none", "rgb": "rgb", "bgr": "bgr"}
LCDFILTER = {"default": "lcddefault", "light": "lcdlight", "legacy": "lcdlegacy", "none": "lcdnone"}

SANS_NAMES = ("sans-serif", "system-ui", "-apple-system", "BlinkMacSystemFont", "Roboto", "Arial",
              "Helvetica", "Helvetica Neue", "Segoe UI")
SF_EXTRA_NAMES = ("SF Pro", ".SF NS", "SF UI Text")

# macOS details for the SF mapping: Display at 20pt+, SF Mono and New York for their
# generic names, and New York Small's odd Bold/Black weights fixed so bold picks Bold.
SF_RULES = """  <match target="pattern">
    <test name="family" qual="first"><string>SF Pro Text</string></test>
    <test name="size" compare="more_eq"><double>20</double></test>
    <edit name="family" mode="prepend" binding="strong"><string>SF Pro Display</string></edit>
  </match>
""" + "".join(f"""  <match target="pattern">
    <test name="family" qual="any"><string>{name}</string></test>
    <edit name="family" mode="prepend" binding="strong"><string>{target}</string></edit>
  </match>
""" for name, target in (("ui-monospace", "SF Mono"), ("SFMono-Regular", "SF Mono"), ("Menlo", "SF Mono"),
                         ("Monaco", "SF Mono"), ("ui-serif", "New York Small"), ("New York", "New York Small"),
                         ("ui-rounded", "SF Pro Rounded"))) + "".join(f"""  <match target="scan">
    <test name="family"><string>New York Small</string></test>
    <test name="style"><string>{style}</string></test>
    <edit name="weight" mode="assign"><int>{weight}</int></edit>
  </match>
""" for style, weight in (("Bold", 200), ("Bold Italic", 200), ("Black", 210), ("Black Italic", 210)))


# One letter from each of these scripts. A font with none of them is treated as an icon
# font. Written first for fonts without "&", then for fonts without a space.
SCRIPT_PROBES = (0x0410, 0x03B1, 0x0639, 0x4E2D, 0x05D0, 0x0905, 0x0E01, 0x10D0, 0x0531,
                 0x12A0, 0x0B85, 0x0985)
ICON_FAMILIES = (("contains", "Font Awesome"), ("eq", "codicon"), ("eq", "Symbols Nerd Font"),
                 ("eq", "Material Symbols"), ("eq", "Google Symbols"))
NO_DARKEN = ('    <edit name="hinting" mode="assign"><bool>false</bool></edit>\n'
             '    <edit name="embolden" mode="assign"><bool>false</bool></edit>\n')
# Google's pages ask for these by name and only sometimes load them as web fonts.
GOOGLE_SANS_NAMES = ("Google Sans", "Google Sans Text", "Google Sans Display")
# Stem darkening makes its CJK letters too heavy; Noto CJK takes over.
DARKENING_REJECTS = ("Droid Sans Fallback", "Droid Sans Japanese")


def darkening_on(state: State) -> bool:
    return state["freetype_darkening"] in ("all", "strong") or state["small_bold"] == "on"


def icon_rules() -> str:
    """Hinting off for icon fonts, which also turns off autofitter darkening, and no fake bold.
    CFF icon fonts (Font Awesome) still get CFF darkening: FreeType applies it unhinted too."""
    out = "  <!-- Icon fonts: no autofitter darkening, no fake bold. -->\n"
    for first in (0x0026, 0x0020):
        out += '  <match target="font">\n'
        out += "".join(f'    <test name="charset" compare="not_contains"><charset><int>0x{c:04X}</int></charset></test>\n'
                       for c in (first, *SCRIPT_PROBES))
        out += NO_DARKEN + "  </match>\n"
    for compare, family in ICON_FAMILIES:
        out += ('  <match target="font">\n'
                f'    <test name="family" qual="any" compare="{compare}"><string>{family}</string></test>\n'
                + NO_DARKEN + "  </match>\n")
    return out


def _hint_edits(style: str, indent: str) -> str:
    enabled = "false" if style == "none" else "true"
    return (f'{indent}<edit name="hinting" mode="assign"><bool>{enabled}</bool></edit>\n'
            f'{indent}<edit name="hintstyle" mode="assign"><const>hint{style}</const></edit>\n')


def render_conf(state: State, rejects: Iterable[str], google_sans: bool = False) -> str:
    """google_sans: the Google Sans Flex package is installed; alias Google's names to it."""
    out = HEADER + "<fontconfig>\n"
    out += '  <match target="font">\n'
    out += '    <edit name="antialias" mode="assign"><bool>true</bool></edit>\n'
    out += f'    <edit name="rgba" mode="assign"><const>{RGBA[state["antialias"]]}</const></edit>\n'
    out += f'    <edit name="lcdfilter" mode="assign"><const>{LCDFILTER[state["lcdfilter"]]}</const></edit>\n'
    out += _hint_edits(state["hinting"], "    ")
    out += "  </match>\n"
    out += '  <match target="font">\n'
    out += '    <test name="spacing" compare="eq"><const>mono</const></test>\n'
    out += _hint_edits(state["mono_hinting"], "    ")
    out += "  </match>\n"
    if state["small_bold"] == "on":
        out += '  <match target="font">\n'
        out += '    <test name="pixelsize" compare="less"><double>14</double></test>\n'
        out += '    <edit name="embolden" mode="assign"><bool>true</bool></edit>\n'
        out += "  </match>\n"
    if google_sans:
        out += "  <!-- Google Sans Flex stands in for Google's fonts when a page does not load them. -->\n"
        out += _aliases(GOOGLE_SANS_NAMES, "Google Sans Flex")
    darken = darkening_on(state)
    if darken:
        out += icon_rules()     # after the hinting and embolden rules, so it wins
    rejects = list(rejects)
    if rejects or darken:
        out += "  <selectfont><rejectfont>\n"
        if rejects:
            out += "    <!-- System files replaced by fontlab's copies in ~/.local/share/fonts/fontlab. -->\n"
            out += "".join(f"    <glob>{escape(g)}</glob>\n" for g in rejects)
        if darken:
            out += "".join(f'    <pattern><patelt name="family"><string>{f}</string></patelt></pattern>\n'
                           for f in DARKENING_REJECTS)
        out += "  </rejectfont></selectfont>\n"
    return out + "</fontconfig>\n"


def system_sans_rewrites() -> list[str]:
    """Families the system config ASSIGNS in place of sans-serif/system-ui.

    Some distros (Omarchy's 50-omarchy.conf) replace the generic name before user rules
    run, so a rule on "sans-serif" never fires. Matching on what it became fixes that."""
    found: list[str] = []
    for f in sorted(paths.SYSTEM_FONTCONFIG_DIR.glob("*.conf")):
        try:
            root = ET.parse(f).getroot()
        except (ET.ParseError, OSError):
            continue
        for match in root.iter("match"):
            tests = {s.text for t in match.findall("test") if t.get("name") == "family" for s in t.iter("string")}
            if not tests & {"sans-serif", "system-ui"}:
                continue
            for edit in match.findall("edit"):
                if edit.get("name") == "family" and edit.get("mode", "").startswith("assign"):
                    found += [s.text for s in edit.iter("string") if s.text and s.text not in found]
    return found


def _aliases(names: Iterable[str], target: str) -> str:
    return "".join(f"""  <match target="pattern">
    <test name="family" qual="any"><string>{escape(n)}</string></test>
    <edit name="family" mode="prepend" binding="strong"><string>{escape(target)}</string></edit>
  </match>
""" for n in names)


def web_conf(state: State, inter_available: bool) -> str | None:
    """None means no file: the system decides."""
    choice = state["web_fonts"]
    if choice == "windows":            # Chromium gets Windows fonts (chromium.py); others keep Inter
        choice = "inter" if inter_available else "system"
    if choice == "system":
        return None
    rewrites = system_sans_rewrites()
    if choice == "inter":
        body = _aliases([*SANS_NAMES, *rewrites], "Inter")
    else:
        body = _aliases([*SANS_NAMES, *SF_EXTRA_NAMES, *rewrites], "SF Pro Text") + SF_RULES
    note = ("  <!-- prepend+strong keeps the rest of the list, so CJK, emoji and icons still fall back. -->\n")
    return HEADER + "<fontconfig>\n" + note + body + "</fontconfig>\n"
